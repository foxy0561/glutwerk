/* Daten beim Laden auf Englisch umstellen */
(function () {
  if (!window.EN) return;
  const W = window.WERTE || {};
  const tr = a => { if (a && ATK_EN[a[0]]) a[0] = ATK_EN[a[0]]; };
  Object.values(W).forEach(w => (w.atk || []).forEach(tr));
  Object.entries(window.MARKER || {}).forEach(([k, m]) => { if (MARKER_EN[k]) m.name = MARKER_EN[k]; (m.atk || []).forEach(tr); });
  Object.keys(PASSIV_EN).forEach(k => { if (window.PASSIV && k in PASSIV) PASSIV[k] = PASSIV_EN[k]; });
  Object.keys(ORTE_EN).forEach(k => {
    if (!window.ORTE || !(k in ORTE)) return;
    if (typeof ORTE[k] === "string") ORTE[k] = ORTE_EN[k]; else if (ORTE[k] && "text" in ORTE[k]) ORTE[k].text = ORTE_EN[k];
  });
  (window.GEGNER_DECKS || []).forEach(d => { d.anzeige = NAMES_EN[d.name] || d.name; });
  [window.RUECKEN, window.FELDER].forEach(o => Object.values(o || {}).forEach(x => { if (NAMES_EN[x.name]) x.name = NAMES_EN[x.name]; if (x.text && NAMES_EN[x.text]) x.text = NAMES_EN[x.text]; }));
})();
